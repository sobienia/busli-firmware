#!/usr/bin/env python3
# gen_airports.py — Generate include/airports.h from OurAirports airports.csv
#
# Usage:
#   python scripts/gen_airports.py path/to/airports.csv
#
# Where to get airports.csv (public domain, updated nightly):
#   https://davidmegginson.github.io/ourairports-data/airports.csv
#
# Keeps large and medium airports that have an IATA code (the code printed on
# tickets, e.g. ZRH, BAH). Stores IATA + ICAO + coordinates so the flight
# tracker can estimate arrival time from the aircraft's live position.

import csv
import sys
import os

def main():
    if len(sys.argv) < 2:
        print("Usage: python gen_airports.py path/to/airports.csv")
        sys.exit(1)

    src_file = sys.argv[1]
    out_file = os.path.join(os.path.dirname(__file__), "..", "include", "airports.h")

    airports = {}
    rows_read = 0

    with open(src_file, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            rows_read += 1
            if row["type"] not in ("large_airport", "medium_airport"):
                continue
            iata = row["iata_code"].strip().upper()
            if len(iata) != 3 or not iata.isalpha():
                continue
            icao = (row["icao_code"] or row["gps_code"] or "").strip().upper()
            if len(icao) != 4:
                icao = ""
            # Prefer a large airport if an IATA code appears twice
            if iata in airports and airports[iata][3] == "large_airport":
                continue
            airports[iata] = (icao, float(row["latitude_deg"]),
                              float(row["longitude_deg"]), row["type"])

    count = len(airports)
    print(f"Read {rows_read} rows -> {count} airports with IATA codes")

    with open(out_file, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Auto-generated by scripts/gen_airports.py — do not edit manually\n")
        f.write("// Source: OurAirports airports.csv (public domain), large + medium airports\n")
        f.write(f"// {count} airports, sorted by IATA code, stored in flash\n")
        f.write("#pragma once\n\n")
        f.write("struct AirportCoord { char iata[4]; char icao[5]; float lat; float lon; };\n\n")
        f.write(f"static const int AIRPORTS_COUNT = {count};\n\n")
        f.write("static const AirportCoord AIRPORTS[] = {\n")
        for iata in sorted(airports):
            icao, lat, lon, _ = airports[iata]
            f.write(f'    {{"{iata}","{icao}",{lat:.4f}f,{lon:.4f}f}},\n')
        f.write("};\n")

    print(f"Written -> {os.path.abspath(out_file)}")

if __name__ == "__main__":
    main()
