#!/usr/bin/env python3
# gen_ca_certs.py — Generate include/ca_certs.h (trusted roots for OTA updates)
#
# Usage:
#   python scripts/gen_ca_certs.py path/to/cacert.pem
#
# Where to get cacert.pem (Mozilla's trusted roots, maintained by curl):
#   https://curl.se/ca/cacert.pem
#
# OTA downloads come from GitHub, whose hosts currently chain to:
#   raw.githubusercontent.com, release-assets.githubusercontent.com → ISRG Root X1
#   github.com                                                       → USERTrust ECC
# A few other major roots are included so a future CA switch by GitHub doesn't
# lock devices out of updates. Re-run this script if GitHub changes CA.

import re
import sys
import os

ROOTS = [
    "ISRG Root X1",
    "ISRG Root X2",
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "DigiCert Global Root G2",
    "DigiCert Global Root G3",
    "GlobalSign Root CA - R3",
]

def main():
    if len(sys.argv) < 2:
        print("Usage: python gen_ca_certs.py path/to/cacert.pem")
        sys.exit(1)

    text = open(sys.argv[1], encoding="utf-8").read().replace("\r\n", "\n")
    # Entry format: name line, "=====" line, optional "# ..." lines, PEM block
    entries = dict(re.findall(
        r"\n([^\n#][^\n]*)\n=+\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----\n.*?-----END CERTIFICATE-----)",
        text, re.S))

    missing = [r for r in ROOTS if r not in entries]
    if missing:
        print("Missing roots: " + ", ".join(missing))
        sys.exit(1)

    out_file = os.path.join(os.path.dirname(__file__), "..", "include", "ca_certs.h")
    with open(out_file, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Auto-generated by scripts/gen_ca_certs.py — do not edit manually\n")
        f.write("// Source: Mozilla CA bundle (https://curl.se/ca/cacert.pem)\n")
        f.write("// Trusted roots for OTA update downloads (GitHub). One PEM string with\n")
        f.write("// several certificates — mbedTLS parses all of them.\n")
        f.write("#pragma once\n\n")
        f.write("static const char OTA_ROOT_CAS[] =\n")
        for name in ROOTS:
            f.write(f"    // {name}\n")
            for line in entries[name].split("\n"):
                f.write(f'    "{line}\\n"\n')
        f.write("    ;\n")

    print(f"Wrote {len(ROOTS)} roots -> {os.path.abspath(out_file)}")

if __name__ == "__main__":
    main()
