# -----------------------------------------------------------------------------
# gen_flap_digits.ps1 - digits for the split-flap clock -> include/flap_digits.h
# -----------------------------------------------------------------------------
# Renders 0-9 smoothed (16 levels, 4 bits per pixel) into a FLAP_W x FLAP_H
# cell each, all with the same size and baseline, centred horizontally. The
# device blends them onto the flap colour, so curves have no stair steps.
#
# Font: Barlow Condensed SemiBold (SIL Open Font License), from
#   https://github.com/google/fonts/raw/main/ofl/barlowcondensed/BarlowCondensed-SemiBold.ttf
#
# Usage (Windows PowerShell):
#   powershell -ExecutionPolicy Bypass -File scripts\gen_flap_digits.ps1 -Font <path to the .ttf>
# -----------------------------------------------------------------------------
param([Parameter(Mandatory = $true)][string]$Font, [string]$Out = "")
if (-not $Out) { $Out = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) "..\include\flap_digits.h" }

Add-Type -AssemblyName System.Drawing
$W = 92; $H = 150; $DigitH = 116      # cell size; height of the digits in pixels

$pfc = New-Object System.Drawing.Text.PrivateFontCollection
$pfc.AddFontFile((Resolve-Path $Font).Path)
$family = $pfc.Families[0]
$fmt = [System.Drawing.StringFormat]::GenericTypographic

function Get-Path([string]$s, [float]$em) {
    $p = New-Object System.Drawing.Drawing2D.GraphicsPath
    $p.AddString($s, $family, [int][System.Drawing.FontStyle]::Regular, $em, (New-Object System.Drawing.PointF 0, 0), $fmt)
    return $p
}

# Scale so that "0" is $DigitH tall; all digits share that size and baseline
$probe = (Get-Path "0" 100).GetBounds()
$em = 100 * $DigitH / $probe.Height
$ref = (Get-Path "0" $em).GetBounds()
$dy = ($H - $ref.Height) / 2 - $ref.Y

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Generated by scripts/gen_flap_digits.ps1 - split-flap clock digits, don't edit.")
[void]$sb.AppendLine("// Barlow Condensed SemiBold (SIL Open Font License). 4 bits per pixel (0 = flap,")
[void]$sb.AppendLine("// 15 = digit colour), two pixels per byte, high nibble first, rows top to bottom.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("#include <Arduino.h>")
[void]$sb.AppendLine("#define FLAP_W $W")
[void]$sb.AppendLine("#define FLAP_H $H")
[void]$sb.AppendLine("static const uint8_t FLAP_DIGITS[10][$($W * $H / 2)] PROGMEM = {")

for ($d = 0; $d -le 9; $d++) {
    $bmp = New-Object System.Drawing.Bitmap $W, $H
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $g.Clear([System.Drawing.Color]::Black)
    $path = Get-Path "$d" $em
    $b = $path.GetBounds()
    $m = New-Object System.Drawing.Drawing2D.Matrix
    $m.Translate(($W - $b.Width) / 2 - $b.X, $dy)
    $path.Transform($m)
    $g.FillPath([System.Drawing.Brushes]::White, $path)
    $g.Dispose()

    $bytes = New-Object System.Collections.Generic.List[string]
    for ($y = 0; $y -lt $H; $y++) {
        for ($x = 0; $x -lt $W; $x += 2) {
            $a = [int][math]::Round($bmp.GetPixel($x, $y).R * 15 / 255)
            $b2 = [int][math]::Round($bmp.GetPixel($x + 1, $y).R * 15 / 255)
            $bytes.Add(("0x{0:X2}" -f (($a -shl 4) -bor $b2)))
        }
    }
    $bmp.Dispose()
    [void]$sb.AppendLine("  { // $d")
    for ($i = 0; $i -lt $bytes.Count; $i += 23) {
        $n = [math]::Min(23, $bytes.Count - $i)
        [void]$sb.AppendLine("    " + ($bytes.GetRange($i, $n) -join ",") + ",")
    }
    [void]$sb.AppendLine("  },")
}
[void]$sb.AppendLine("};")
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $Out)).Path + "\" + (Split-Path $Out -Leaf), $sb.ToString())
Write-Output "Wrote $Out ($($W * $H / 2 * 10) bytes of digits)"
